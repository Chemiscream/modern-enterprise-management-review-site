/* ================= 图示补充（第十九批）：ch04 归因理论 =================
   课件第 62—65 页：
     海德 1958 最早提出归因问题；凯利 1967《社会心理学的归因理论》
     凯利把归因分为「多线索归因」（多次观察同类行为）与「单线索归因」（一次观察）
     三方面因素：①客观刺激物 ②行动者 ③所处关系或情境
       其中「行动者」属**内部归因**；「客观刺激物」和「情境」属**外部归因**
     三种行为信息：
       ①差异性：行为者是否在同类其它情况下做出相同反应 → 差异**大** → **外部**归因
       ②一贯性：是否在任何情境任何时候对同一刺激物做相同反应 → 一贯性**高** → **内部**归因
       ③一致性：其他人对同一情景是否也做出相同反应 → 一致性**高** → **外部**归因
     归因错误：基本归因错误（低估外部、高估内部）；自我服务偏见（成功归内、失败归外）
*/
